-- ---------------------------------------------------------------------------
-- Confirmação de presença em evento — e o cancelamento dela.
--
-- O PROBLEMA
-- ----------
-- "Confirmar presença" chamava `recordEventParticipation`, que grava apenas em
-- `localStorage` (src/lib/userStats.ts). Consequências:
--
--   1. A confirmação não saía do aparelho. O organizador não sabia quem ia.
--   2. Não havia como CANCELAR a confirmação: o "cancelamento" do evento é
--      outra coisa (o organizador desmarca o evento inteiro).
--
-- Tabela aditiva. Não toca em `event_participations`, que tem outro contrato.
-- ---------------------------------------------------------------------------

create table if not exists public.event_rsvps (
  id            bigint generated by default as identity primary key,
  event_id      integer not null,
  user_id       integer not null references public.users(id) on delete cascade,
  -- Estado da confirmação. 'confirmed' = vou; 'canceled' = desisti.
  status        text not null default 'confirmed',
  canceled_at   timestamptz,
  canceled_reason text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

alter table public.event_rsvps drop constraint if exists event_rsvps_status_check;
alter table public.event_rsvps
  add constraint event_rsvps_status_check
  check (status in ('confirmed', 'canceled'));

-- Uma linha por pessoa por evento: reconfirmar atualiza em vez de duplicar.
create unique index if not exists event_rsvps_event_user_key
  on public.event_rsvps (event_id, user_id);

create index if not exists event_rsvps_event_idx
  on public.event_rsvps (event_id, status);

alter table public.event_rsvps enable row level security;

-- Leitura: a própria confirmação. A gestão lê pelo painel com chave de serviço
-- (a tabela `users` guarda senha em texto, então não abrimos leitura ampla).
drop policy if exists "event_rsvps_own_read" on public.event_rsvps;
create policy "event_rsvps_own_read"
  on public.event_rsvps for select
  to authenticated
  using (false);

revoke all on public.event_rsvps from anon, authenticated;
grant select on public.event_rsvps to authenticated;

do $$
begin
  if to_regclass('public.event_rsvps') is null then
    raise exception 'Migration incompleta: event_rsvps não foi criada';
  end if;
end $$;
